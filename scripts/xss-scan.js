#!/usr/bin/env node
"use strict";
// Usage: node scripts/xss-scan.js   (exit 1 when a hole is found). Same check the test suite runs.
const fs = require("fs");
const path = require("path");
const { scanSource, scanHtml } = require("../lib/xss-scan");

const ROOT = path.join(__dirname, "..", "public");
const SKIP = new Set(["premium-looks-preview.html", "sections-preview.html"]); // generated by scripts, not hand-written pages

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return files(p);
    return /\.(html|js)$/.test(e.name) && !SKIP.has(e.name) ? [p] : [];
  });
}

function scanAll(root = ROOT) {
  const out = [];
  for (const f of files(root)) {
    const src = fs.readFileSync(f, "utf8");
    const rel = path.relative(path.join(__dirname, ".."), f);
    try { out.push(...(f.endsWith(".html") ? scanHtml(src, rel) : scanSource(src, rel))); }
    catch (e) { out.push({ file: rel, line: 0, expr: "", why: `could not parse: ${e.message.slice(0, 80)}` }); }
  }
  return out;
}

if (require.main === module) {
  const found = scanAll();
  for (const f of found) console.log(`${f.file}:${f.line}  ${f.why}\n    ${f.expr}`);
  console.log(found.length ? `\n${found.length} unescaped value(s) in HTML.` : "No unescaped values in HTML.");
  process.exit(found.length ? 1 : 0);
}
module.exports = { scanAll };
